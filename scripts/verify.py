#!/usr/bin/env python3
"""Verify generated JSON-format Clash YAML with an isolated Mihomo process."""
import argparse
import json
import ipaddress
from pathlib import Path
import secrets
import shutil
import socket
import subprocess
import tempfile
import time
import urllib.parse
import urllib.request


def find_core():
    mac = Path('/Applications/Clash Verge.app/Contents/MacOS/verge-mihomo')
    return str(mac) if mac.is_file() else shutil.which('mihomo')


def free_port():
    with socket.socket() as s:
        s.bind(('127.0.0.1', 0))
        return s.getsockname()[1]


def verify(client, core=None):
    core = core or find_core()
    if not core:
        raise RuntimeError('Mihomo/Clash Verge core unavailable; install it or provide --core before deployment')
    socks, api = free_port(), free_port()
    while api == socks:
        api = free_port()
    token = secrets.token_urlsafe(24)
    d = {'mixed-port': socks, 'external-controller': '127.0.0.1:' + str(api),
         'secret': token, 'allow-lan': False, 'mode': 'rule', 'log-level': 'warning',
         'proxies': client['proxies'], 'proxy-groups': [
             {'name': 'VERIFY', 'type': 'select', 'proxies': [p['name'] for p in client['proxies']]}],
         'rules': ['MATCH,VERIFY']}
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    with tempfile.TemporaryDirectory(prefix='proxy-verify-') as td:
        path = Path(td) / 'test.json'
        path.write_text(json.dumps(d))
        path.chmod(0o600)
        checked = subprocess.run([core, '-t', '-d', td, '-f', str(path)], capture_output=True)
        if checked.returncode:
            raise RuntimeError('Mihomo rejected the generated client configuration')
        with open(Path(td) / 'core.log', 'w') as log:
            proc = subprocess.Popen([core, '-d', td, '-f', str(path)], stdout=log, stderr=log)
            try:
                for _ in range(60):
                    if proc.poll() is not None:
                        raise RuntimeError('Verification core exited unexpectedly')
                    try:
                        req = urllib.request.Request('http://127.0.0.1:%s/version' % api,
                                                     headers={'Authorization': 'Bearer ' + token})
                        opener.open(req, timeout=0.5).close()
                        break
                    except OSError:
                        time.sleep(0.1)
                else:
                    raise RuntimeError('Verification core did not become ready')
                results = []
                for p in client['proxies']:
                    req = urllib.request.Request('http://127.0.0.1:%s/proxies/VERIFY' % api,
                        data=json.dumps({'name': p['name']}).encode(), method='PUT',
                        headers={'Authorization': 'Bearer ' + token, 'Content-Type': 'application/json'})
                    opener.open(req, timeout=3).close()
                    cmd = ['curl', '-sS', '--noproxy', '', '--proxy', 'http://127.0.0.1:' + str(socks),
                           '--connect-timeout', '10', '--max-time', '25']
                    r = subprocess.run(cmd + ['https://www.gstatic.com/generate_204', '-o', '/dev/null',
                                              '-w', '%{http_code}'], capture_output=True, text=True)
                    ip = subprocess.run(cmd + ['https://api.ipify.org'], capture_output=True, text=True)
                    try:
                        ipaddress.ip_address(ip.stdout.strip())
                        valid_ip = True
                    except ValueError:
                        valid_ip = False
                    results.append({'node': p['name'], 'https_status': r.stdout.strip(),
                                    'exit_ip': ip.stdout.strip() if ip.returncode == 0 else None,
                                    'passed': r.returncode == 0 and r.stdout.strip() == '204' and ip.returncode == 0 and valid_ip})
                return results
            finally:
                proc.terminate()
                try:
                    proc.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    proc.kill()
                    proc.wait()


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('client', help='JSON-format .yaml generated by deploy.py')
    p.add_argument('--core')
    a = p.parse_args()
    results = verify(json.loads(Path(a.client).read_text()), a.core)
    print(json.dumps(results, indent=2))
    raise SystemExit(0 if all(r['passed'] for r in results) else 1)
